export function t(key) {
  return I[state.lang]?.[key] ?? I.en[key];
}

export function pickLang(raw, nav) {
  if (raw === "en" || raw === "es" || raw === "zh") return raw;
  const n = nav || "";
  if (/^es\b/i.test(n)) return "es";
  if (/^zh\b/i.test(n)) return "zh";
  return "en";
}
